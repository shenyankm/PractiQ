-- Purpose: Define subjects, question types, question banks, bank ownership/favorites, and bank-level practice stats.
-- PostgreSQL-only schema fragment. Apply after earlier numbered fragments in db/*/*.sql order.

CREATE TABLE subjects (
    subject_id VARCHAR(32) PRIMARY KEY,
    display_name VARCHAR(64) NOT NULL,
    CONSTRAINT chk_subjects_subject_id_not_blank CHECK (btrim(subject_id) <> ''),
    CONSTRAINT chk_subjects_display_name_not_blank CHECK (btrim(display_name) <> '')
);

