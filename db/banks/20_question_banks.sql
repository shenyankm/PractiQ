    ('general', 'General');

CREATE TABLE question_types (
    type_id VARCHAR(64) PRIMARY KEY,
    subject_id VARCHAR(32) NOT NULL REFERENCES subjects(subject_id) ON DELETE RESTRICT,
    display_name VARCHAR(128) NOT NULL,
    scope VARCHAR(16) NOT NULL DEFAULT 'question',
    default_answer_mode VARCHAR(32),
    CONSTRAINT chk_question_types_type_id_not_blank CHECK (btrim(type_id) <> ''),
    CONSTRAINT chk_question_types_display_name_not_blank CHECK (btrim(display_name) <> ''),
    CONSTRAINT chk_question_types_scope CHECK (scope IN ('question', 'group', 'hybrid')),
    CONSTRAINT chk_question_types_answer_mode CHECK (
        default_answer_mode IS NULL
        OR default_answer_mode IN ('choice', 'true_false', 'fill_blank', 'short_answer')
    )
);

CREATE UNIQUE INDEX uq_question_types_subject_type ON question_types (subject_id, type_id);

