    CONSTRAINT chk_question_import_jobs_totals_nonnegative CHECK (
        total_questions >= 0
        AND imported_questions >= 0
        AND page_count >= 0
        AND wave_count >= 0
        AND failed_block_count >= 0
        AND block_count >= 0
        AND completed_block_count >= 0
        AND retry_count >= 0
        AND high_risk_block_count >= 0
        AND review_item_count >= 0
    ),
    CONSTRAINT chk_question_import_jobs_counts_consistent CHECK (
        imported_questions <= total_questions
