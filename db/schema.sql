    last_error TEXT,
    current_step_code VARCHAR(64),
    current_step_label VARCHAR(128),
    overall_progress_percent DOUBLE PRECISION,
    step_progress_percent DOUBLE PRECISION,
    current_target_kind VARCHAR(64),
    current_target_name VARCHAR(512),
    last_event_id BIGINT,
