import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { contractSource as source, schemaFor, type Schema } from "../desktop/contract-source.ts";

const root = new URL("../", import.meta.url);
function write(path: string, content: string): void {
  const target = new URL(path, root);
  if (readFileSync(target, "utf8") === content) return;
  if (process.argv.includes("--check")) throw new Error(`Contract export changed: ${fileURLToPath(target)}`);
  writeFileSync(target, content);
}
function type(node: Schema): string {
  if (node.$ref) return node.$ref.split("/").at(-1)!;
  if (Object.hasOwn(node, "const")) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(" | ");
  if (node.anyOf || node.oneOf) return (node.anyOf ?? node.oneOf)!.map(type).join(" | ");
  if (node.type === "array") return `(${type(node.items!)})[]`;
  if (node.type === "object") {
    if (!node.properties) return `Record<string, ${typeof node.additionalProperties === "object" ? type(node.additionalProperties) : "unknown"}>`;
    return `{ ${Object.entries(node.properties).map(([key, value]) => `${JSON.stringify(key)}${node.required?.includes(key) ? "" : "?"}: ${type(value)}`).join("; ")} }`;
  }
  if (["string", "boolean", "null"].includes(node.type ?? "")) return node.type!;
  if (["number", "integer"].includes(node.type ?? "")) return "number";
  if (Object.keys(node).every(key => ["title", "description", "default"].includes(key))) return "unknown";
  throw new Error(`Unsupported schema type: ${JSON.stringify(node)}`);
}
