write("src-tauri/contracts.json", JSON.stringify(Object.fromEntries(Object.entries(source.exports).map(([key, name]) => [key, schemaFor(name)])), null, 2) + "\n");
const definitions = structuredClone(source.definitions) as Record<string, Schema>;
definitions.ParsedQuestion.required = ["stem", "answerMode", "questionTypeId", "options", "items", "answerPayload", "contentBlocks", "confidence", "needsReview", "missingFields"].sort();
const answerFields = Object.assign({}, ...Object.entries(definitions).filter(([name]) => name.endsWith("AnswerPayload") || name === "ShortAnswerPayload").map(([, node]) => node.properties));
const header = "// Generated by app/scripts/export-contracts.ts. Do not edit.";
const lines = [header];
for (const [name, node] of Object.entries(definitions)) {
  if (!source.wireModels.includes(name)) lines.push(`export type ${name} = ${type(node)};`);
}
lines.push(`export type Answer = ${type({ type: "object", properties: answerFields })};`);
lines.push('export type Question = Omit<ParsedQuestion, "answerPayload"> & { answerPayload: Answer | null };');
lines.push(`export type DocumentResult = ${type(definitions.DocumentParseResult)};`);
for (const name of source.wireModels) lines.push(`export type ${name} = ${type(definitions[name])};`);
const metadata = source.metadata;
const strings = (values: string[]) => `[${values.map(value => JSON.stringify(value)).join(", ")}]`;
lines.push(`export const QUESTION_KIND_MODES = {${Object.entries(metadata.questionKindModes).map(([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`).join(", ")}} as const;`);
lines.push(`export type DocumentSourceType = ${metadata.documentSourceTypes.map(value => JSON.stringify(value)).join(" | ")};`);
