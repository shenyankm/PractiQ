CREATE VIEW v_bank_question_items AS
SELECT
    bgl.bank_id,
    g.id AS group_id,
    q.id AS question_id,
    'grouped' AS item_scope,
    bgl.sort_order AS bank_sort_order,
    gql.sort_order AS group_sort_order,
    gql.question_no AS question_no,
    bgl.status AS bank_link_status,
    q.business_type,
    q.subject_id,
    q.question_type_id,
    q.answer_mode,
    q.choice_variant,
    q.content_mode,
    q.stem,
    q.analysis,
    q.status AS question_status,
    q.source_type,
    q.source_ref,
    q.source_job_id,
    q.imported_by,
    q.hierarchy_level,
    q.hierarchy_path,
    q.chapter_ref,
    q.chapter_title,
    q.chapter_order,
    g.business_type AS group_business_type,
    g.subject_id AS group_subject_id,
    g.group_type_id,
    g.content_mode AS group_content_mode,
    g.title AS group_title,
    g.instructions AS group_instructions,
    g.source_ref AS group_source_ref,
    g.parent_group_id,
    g.source_job_id AS group_source_job_id,
    g.imported_by AS group_imported_by,
    g.hierarchy_level AS group_hierarchy_level,
    g.hierarchy_path AS group_hierarchy_path,
    g.chapter_ref AS group_chapter_ref,
    g.chapter_title AS group_chapter_title,
    g.chapter_order AS group_chapter_order
FROM bank_group_links bgl
JOIN question_groups g ON g.id = bgl.group_id
JOIN group_question_links gql ON gql.group_id = g.id
JOIN questions q ON q.id = gql.question_id
UNION ALL
SELECT
    bql.bank_id,
    CAST(NULL AS BIGINT) AS group_id,
    q.id AS question_id,
    'standalone' AS item_scope,
    bql.sort_order AS bank_sort_order,
    CAST(NULL AS INTEGER) AS group_sort_order,
    bql.question_no AS question_no,
    bql.status AS bank_link_status,
    q.business_type,
    q.subject_id,
    q.question_type_id,
    q.answer_mode,
    q.choice_variant,
    q.content_mode,
    q.stem,
    q.analysis,
    q.status AS question_status,
    q.source_type,
    q.source_ref,
    q.source_job_id,
    q.imported_by,
    q.hierarchy_level,
    q.hierarchy_path,
    q.chapter_ref,
    q.chapter_title,
    q.chapter_order,
    CAST(NULL AS VARCHAR(64)) AS group_business_type,
    CAST(NULL AS VARCHAR(32)) AS group_subject_id,
    CAST(NULL AS VARCHAR(64)) AS group_type_id,
    CAST(NULL AS VARCHAR(32)) AS group_content_mode,
    CAST(NULL AS VARCHAR(512)) AS group_title,
    CAST(NULL AS VARCHAR(1024)) AS group_instructions,
    CAST(NULL AS VARCHAR(128)) AS group_source_ref,
    CAST(NULL AS BIGINT) AS parent_group_id,
    CAST(NULL AS BIGINT) AS group_source_job_id,
    CAST(NULL AS BIGINT) AS group_imported_by,
    CAST(NULL AS INTEGER) AS group_hierarchy_level,
    CAST(NULL AS VARCHAR(512)) AS group_hierarchy_path,
    CAST(NULL AS VARCHAR(128)) AS group_chapter_ref,
    CAST(NULL AS VARCHAR(512)) AS group_chapter_title,
    CAST(NULL AS INTEGER) AS group_chapter_order
FROM bank_question_links bql
JOIN questions q ON q.id = bql.question_id;

