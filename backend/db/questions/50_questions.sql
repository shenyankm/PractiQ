CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type TEXT NOT NULL DEFAULT 'standalone',
    subject_id VARCHAR(32) NOT NULL DEFAULT 'general' REFERENCES subjects(subject_id) ON DELETE RESTRICT,
    question_type_id VARCHAR(64) NOT NULL DEFAULT 'generic_answer_mode' REFERENCES question_types(type_id) ON DELETE RESTRICT,
    answer_mode TEXT NOT NULL,
    choice_variant TEXT,
    hierarchy_level INTEGER NOT NULL DEFAULT 1,
    hierarchy_path VARCHAR(512),
    chapter_ref VARCHAR(128),
    chapter_title VARCHAR(512),
    chapter_order INTEGER,
    content_mode VARCHAR(32),
    stem TEXT NOT NULL,
    analysis TEXT,
    detail_payload TEXT NOT NULL DEFAULT '{}',
    status TEXT NOT NULL DEFAULT 'draft',
    source_type TEXT NOT NULL DEFAULT 'parsed',
    source_ref VARCHAR(128),
    source_job_id BIGINT REFERENCES question_import_jobs(id) ON DELETE SET NULL,
    imported_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_questions_business_type_not_blank CHECK (btrim(business_type) <> ''),
    CONSTRAINT chk_questions_answer_mode CHECK (
        answer_mode IN ('choice', 'true_false', 'fill_blank', 'short_answer')
    ),
    CONSTRAINT chk_questions_choice_variant CHECK (
        choice_variant IS NULL OR choice_variant IN ('single', 'multiple')
    ),
    CONSTRAINT chk_questions_hierarchy_level CHECK (hierarchy_level >= 1),
    CONSTRAINT chk_questions_chapter_order CHECK (chapter_order IS NULL OR chapter_order > 0),
    CONSTRAINT chk_questions_content_mode CHECK (
        content_mode IS NULL OR content_mode IN ('text_only', 'mixed_media', 'structured_rich')
    ),
    CONSTRAINT chk_questions_stem_not_blank CHECK (btrim(stem) <> ''),
    CONSTRAINT chk_questions_status CHECK (status IN ('draft', 'active', 'archived')),
    CONSTRAINT chk_questions_source_type CHECK (source_type IN ('manual', 'imported', 'parsed')),
    CONSTRAINT fk_questions_subject_type
        FOREIGN KEY (subject_id, question_type_id)
        REFERENCES question_types(subject_id, type_id)
        ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_questions_id_subject ON questions (id, subject_id);
CREATE INDEX idx_questions_business_type ON questions (business_type);
CREATE INDEX idx_questions_subject_type ON questions (subject_id, question_type_id);
CREATE INDEX idx_questions_status_type ON questions (status, question_type_id, id);
CREATE INDEX idx_questions_content_mode ON questions (content_mode);
CREATE INDEX idx_questions_source_ref ON questions (source_type, source_ref);
CREATE INDEX idx_questions_source_job ON questions (source_job_id);
CREATE INDEX idx_questions_imported_by ON questions (imported_by);
CREATE INDEX idx_questions_chapter ON questions (chapter_ref, chapter_order);
CREATE INDEX idx_questions_stem_trgm ON questions USING GIN (stem gin_trgm_ops);
